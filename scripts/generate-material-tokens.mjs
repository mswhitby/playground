// Generate once from Google's pinned Material Color Utilities 0.4.0 (Apache-2.0).
// Pass the extracted package directory; generated CSS is committed for offline use.
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {writeFile,readFile,readdir,cp,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
const temporary=await mkdtemp(resolve(tmpdir(),'material-colors-'));
await cp(resolve(process.argv[2]),temporary,{recursive:true});
async function fixImports(directory){for(const entry of await readdir(directory,{withFileTypes:true})){const path=resolve(directory,entry.name);if(entry.isDirectory())await fixImports(path);else if(entry.name.endsWith('.js')){let source=await readFile(path,'utf8');source=source.replace(/(from\s+['"])(\.[^'"]+)(['"])/g,(all,start,relative,end)=>start+relative+(/\.[a-z]+$/i.test(relative)?'':'.js')+end);await writeFile(path,source)}}}
await fixImports(temporary);
const root=pathToFileURL(temporary+'/');
const {SchemeTonalSpot}=await import(new URL('scheme/scheme_tonal_spot.js',root));
const {Hct}=await import(new URL('hct/hct.js',root));
const {argbFromHex,hexFromArgb}=await import(new URL('utils/string_utils.js',root));
const roles=['primary','onPrimary','primaryContainer','onPrimaryContainer','secondary','onSecondary','secondaryContainer','onSecondaryContainer','tertiary','onTertiary','tertiaryContainer','onTertiaryContainer','surface','onSurface','surfaceContainerLowest','surfaceContainerLow','surfaceContainer','surfaceContainerHigh','surfaceContainerHighest','onSurfaceVariant','outline','outlineVariant','inverseSurface','inverseOnSurface','error','onError','errorContainer','onErrorContainer','scrim'];
let css='/* Generated by Google Material Color Utilities 0.4.0. Purple #6750A4; Tonal Spot; 2025 spec; standard contrast. */\n';
for(const dark of [false,true]){
 const scheme=new SchemeTonalSpot(Hct.fromInt(argbFromHex('#6750A4')),dark,0,'2025');
 css+=(dark?':root[data-theme="dark"]':':root, :root[data-theme="light"]')+'{\n';
 for(const role of roles)css+=` --md-sys-color-${role.replace(/[A-Z]/g,c=>'-'+c.toLowerCase())}:${hexFromArgb(scheme[role])};\n`;
 css+=` color-scheme:${dark?'dark':'light'};\n}\n`;
}
await writeFile(new URL('../public/material-tokens.css',import.meta.url),css);

await rm(temporary,{recursive:true,force:true});
